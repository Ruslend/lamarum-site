function buildInitialSlot(id, daysFromToday, time, status) {
  const date = new Date();
  date.setDate(date.getDate() + daysFromToday);
  const isoDate = formatLocalIsoDate(date);
  const plainDate = parsePlainDate(isoDate);
  const slotDate = new Date(plainDate.year, plainDate.month - 1, plainDate.day, 12, 0, 0);
  const weekday = new Intl.DateTimeFormat("ru-RU", {
    weekday: "long",
  }).format(slotDate);
  const displayDate = new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: "long",
  }).format(slotDate);
  const normalizedWeekday = weekday.charAt(0).toUpperCase() + weekday.slice(1);

  return {
    id,
    weekday: normalizedWeekday,
    date: isoDate,
    time,
    status,
    label: `${normalizedWeekday}, ${displayDate}, ${time}`,
  };
}

function parsePlainDate(value) {
  const [year, month, day] = String(value).slice(0, 10).split("-").map(Number);

  return { year, month, day };
}

function formatLocalIsoDate(value) {
  const year = value.getFullYear();
  const month = String(value.getMonth() + 1).padStart(2, "0");
  const day = String(value.getDate()).padStart(2, "0");

  return `${year}-${month}-${day}`;
}

